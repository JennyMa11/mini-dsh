"""Generate the Mini-dsh repo-level benchmark fixtures and manifest.

These tasks exist because the ``core`` suite is deliberately small and regular: a
scripted model can drive it, which makes it a *harness* test but a poor *capability*
test. Every task here spans at least two modules, has no response script, and is meant
to be run against a real provider.

Two properties are load-bearing:

* **No response script.** A task with a canned response measures the script, not the
  model. These tasks only declare an executable success criterion.
* **A non-obvious fix.** Several fixtures are built so the first plausible edit makes
  a *different* test fail, which is what forces multi-round error recovery instead of
  a single lucky patch.

Run ``python benchmarks/build_repo.py`` to rewrite the committed artifacts.
"""

