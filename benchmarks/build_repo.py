def _write_fixture(task_id: str, files: dict[str, str]) -> None:
    fixture_root = ROOT / "fixtures" / task_id
    for relative, content in files.items():
        destination = fixture_root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")


def main() -> None:
    manifest_tasks: list[dict[str, object]] = []
    for task in TASKS:
        task_id = str(task["id"])
        files = task["files"]
        assert isinstance(files, dict)
        _write_fixture(task_id, files)
        manifest_tasks.append(
            {
                "id": task_id,
                "goal": task["goal"],
                "workspace": f"fixtures/{task_id}",
                "success_argv": UNITTEST,
                "test_argv": UNITTEST,
                "timeout_seconds": 120,
                "tags": task["tags"],
                "category": task["category"],
                "repo_commit": _input_digest(files),
                "seed": 0,
                "model": "provider",
                "budget": BUDGET,
                "isolation": ISOLATION,
            }
        )
    manifest = {
        "name": "mini-dsh-repo",
        "schema_version": "2.0",
        "tasks": manifest_tasks,
    }
    ROOT.mkdir(parents=True, exist_ok=True)
    (ROOT / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=False) + "\n", encoding="utf-8"
    )
    sys.stdout.write(f"wrote {len(manifest_tasks)} tasks to {ROOT / 'manifest.json'}\n")


if __name__ == "__main__":
    main()
