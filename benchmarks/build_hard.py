def _with_header(files: dict[str, str]) -> dict[str, str]:
    """Return files with a generated-source header on Python modules."""
    return {
        name: (GENERATED_HEADER + content if name.endswith(".py") else content)
        for name, content in files.items()
    }


def _digest(files: dict[str, str]) -> str:
    """Pin file contents with a deterministic digest over names and bodies."""
    digest = hashlib.sha256()
    for name in sorted(files):
        digest.update(name.encode())
        digest.update(files[name].encode())
    return f"sha256:{digest.hexdigest()[:16]}"


