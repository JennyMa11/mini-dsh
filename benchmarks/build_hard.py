def _minimum_checks(overlay: dict[str, str]) -> int:
    """Count the held-out test methods, so the verifier can refuse a vacuous suite."""
    total = 0
    for name, content in overlay.items():
        if not name.endswith(".py") or "verification_tests/test_" not in name:
            continue
        total += sum(1 for line in content.splitlines() if line.strip().startswith("def test_"))
    return total


def _write(base: Path, files: dict[str, str]) -> None:
    for relative, content in files.items():
        destination = base / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")


