"""Generate the Mini-dsh hard-suite fixtures, held-out verifiers and solutions.

Why this suite exists
---------------------

Every other suite in this repository verifies by re-running tests the agent can read
and edit, so what it measures is *compliance with the visible tests* rather than
*correctness against a specification*.  That is why they all saturate: a model that
greens the visible suite scores 100% whether or not it honoured the contract.

A task here is built so that greening the visible suite is not sufficient.  Each
workspace ships a **smoke subset** of the specification's tests, and the real checks
live in a `verification/<task_id>/` overlay that the runner copies in *after* the
agent finishes and *before* the success command runs.  The overlay also supplies
`run_verification.py`, so the criterion itself is a file the agent never saw.

Fairness, stated deliberately
-----------------------------

A suite that manufactures failures by hiding requirements measures nothing.  Three
rules keep these tasks fair:

* **The specification is complete and in the workspace.**  Every contract point a
  held-out check exercises is written in the module docstring, including the ones the
  smoke subset never touches.  A failure therefore means the stated contract was not
  implemented, not that a requirement was concealed.
* **The agent is told the smoke subset is not the criterion.**  Each task's goal says
  so, and points at the docstring.
* **A committed reference solution passes.**  Without it a 0% result cannot be told
  apart from a broken fixture; `tests/test_hard_suite.py` runs both directions
  offline, with no model.

Run ``python benchmarks/build_hard.py`` to rewrite the committed artifacts.
"""

