CONFIG_SOLUTION = {
    "config/resolve.py": GENERATED_HEADER
    + r'''"""Resolve configuration from layered sources.

``resolve(defaults, env=None, cli=None)`` returns the effective configuration, taking
each key from the highest-priority source that supplies it::

    cli  >  env  >  defaults

Contract
--------

* ``defaults`` maps every known key to its default value, and its value for a key also
  declares that key's type.
* ``env`` and ``cli`` map keys to **strings**, or to ``None``.
* A source that maps a key to ``None`` has not supplied it: the key falls through to
  the next source down.  A key whose only override is ``None`` keeps its default.
* The result contains exactly the keys of ``defaults``.
* A key in ``env`` or ``cli`` that is not in ``defaults`` is rejected with
  ``KeyError`` naming that key.
* An override is coerced to the type of the matching default:

  - ``bool``: ``"true"``, ``"1"``, ``"yes"`` and ``"on"`` are ``True``;
    ``"false"``, ``"0"``, ``"no"`` and ``"off"`` are ``False``.  Both sets are matched
    case-insensitively and ignore surrounding whitespace.  Any other spelling raises
    ``ValueError`` naming the key.
  - ``int`` / ``float``: parsed with ``int()`` / ``float()``; a parse failure raises
    ``ValueError`` naming the key.
  - ``str``: returned unchanged.

* ``defaults``, ``env`` and ``cli`` are never mutated.
"""

_TRUE = frozenset({"true", "1", "yes", "on"})
_FALSE = frozenset({"false", "0", "no", "off"})


def _coerce(key, raw, default):
    """Return ``raw`` as the type ``default`` declares, or raise naming ``key``."""
    # `bool` first: it is a subclass of `int`, so the numeric branch would otherwise
    # swallow it and parse "yes" as an int.
    if isinstance(default, bool):
        lowered = raw.strip().lower()
        if lowered in _TRUE:
            return True
        if lowered in _FALSE:
            return False
        raise ValueError(f"invalid boolean for {key}: {raw!r}")
    if isinstance(default, (int, float)):
        try:
            return type(default)(raw.strip())
        except ValueError as exc:
            raise ValueError(f"invalid {type(default).__name__} for {key}: {raw!r}") from exc
    return raw


def resolve(defaults, env=None, cli=None):
    """Return the effective configuration; see the module docstring."""
    # Copied so that rejecting an unknown key cannot be confused with mutation, and so
    # that a caller holding a mutable mapping cannot change it under us mid-resolution.
    layers = (dict(env or {}), dict(cli or {}))
    for layer in layers:
        for key in layer:
            if key not in defaults:
                raise KeyError(key)
    result = {}
    for key, default in defaults.items():
        raw = None
        for layer in reversed(layers):  # highest priority first
            if layer.get(key) is not None:
                raw = layer[key]
                break
        result[key] = default if raw is None else _coerce(key, raw, default)
    return result
'''
}


