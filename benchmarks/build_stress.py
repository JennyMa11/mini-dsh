"""Generate the Mini-dsh stress benchmark suite.

The core suite answers "does the harness work?". This suite answers "can the
harness *measure* the thing it claims to measure?" — it contains tasks whose
outcome is sensitive to one harness variable at a time:

* ``stress-long-history``   — 18 steps, so context strategies must differ.
* ``stress-large-output``   — a 75 KB tool result, so output management must differ.
* ``stress-denied-action``  — denied commands, denied tools, and sandbox escapes,
  so the permission counters must be non-zero.

Run ``python benchmarks/build_stress.py`` to rewrite the committed artifacts.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent / "stress"
UNITTEST = ["python", "-m", "unittest", "discover", "-s", "."]
VERIFY = ["python", "verify.py"]
GENERATED_HEADER = "# Generated by benchmarks/build_stress.py; edit the generator instead.\n"

PARTS = 16
LOG_LINES = 3_000


def _call(call_id: str, name: str, arguments: dict[str, Any]) -> dict[str, Any]:
    return {"call_id": call_id, "name": name, "arguments": arguments}


def _fixture(files: dict[str, str]) -> dict[str, str]:
    """Return fixture files with a generated-source header on Python modules."""
    return {
        name: (GENERATED_HEADER + content if name.endswith(".py") else content)
        for name, content in files.items()
    }


def _input_digest(files: dict[str, str]) -> str:
    """Pin the fixture contents with a deterministic content digest."""
    digest = hashlib.sha256()
    for name in sorted(files):
        digest.update(name.encode())
        digest.update(files[name].encode())
    return f"sha256:{digest.hexdigest()[:16]}"


def _tool_step(call: dict[str, Any], *, output_tokens: int = 24) -> dict[str, Any]:
    """Wrap one tool call in a provider-neutral scripted response."""
    return {"content": "", "tool_calls": [call], "output_tokens": output_tokens}


def _script(steps: list[dict[str, Any]], answer: str) -> list[dict[str, Any]]:
    """Wrap every tool call and append a terminal answer step.

    ``input_tokens`` is deliberately omitted: the scripted adapter then measures the
    context it actually received, which is what makes the ablations comparable.
    """
    return [*[_tool_step(call) for call in steps], {"content": answer, "output_tokens": 40}]


def _long_history() -> dict[str, Any]:
    """Eighteen steps of work: enough history for a window or summary to bite."""
    files: dict[str, str] = {}
    steps: list[dict[str, Any]] = []
    for index in range(PARTS):
        name = f"part_{index:02d}"
        files[f"{name}.py"] = "VALUE = 0\n"
        steps.append(
            _call(
                f"patch-{index:02d}",
                "patch_file",
                {
                    "path": f"{name}.py",
                    "expected": "VALUE = 0",
                    "replacement": f"VALUE = {index + 1}",
                },
            )
        )
    files["verify.py"] = (
        "import importlib\n\n"
        f"for index in range({PARTS}):\n"
        '    module = importlib.import_module(f"part_{index:02d}")\n'
        "    assert module.VALUE == index + 1, (index, module.VALUE)\n"
        'print("ok")\n'
    )
    files["docs/guide.md"] = (
        "# Module value guide\n\n"
        "Every module named `part_NN.py` must expose a single `VALUE` constant.\n"
        "The constant equals the two-digit module index plus one, so `part_00.py`\n"
        "holds `VALUE = 1` and `part_15.py` holds `VALUE = 16`.\n\n"
        + "\n".join(
            f"- `part_{index:02d}.py`: set `VALUE` to {index + 1} before running the suite."
            for index in range(PARTS)
        )
        + "\n"
    )
    steps.append(_call("run-tests", "test", {}))
    return {
        "id": "stress-long-history",
        "category": "long-history",
        "goal": (
            "Set the VALUE constant in every part_NN.py module to the module index plus one, "
            "then run the test suite."
        ),
        "files": _fixture(files),
        "steps": _script(steps, "Set all 16 VALUE constants and the unit test passes."),
        "test": UNITTEST,
        "success": VERIFY,
        "budget": {"max_steps": 30, "max_tokens": 400_000, "max_tool_calls": 40},
    }


def _large_output() -> dict[str, Any]:
    """A single 75 KB observation: enough for truncation and offload to matter."""
    log = "".join(
        f"2026-01-01T00:00:{index % 60:02d}Z event {index:05d} ok\n" for index in range(LOG_LINES)
    )
    files = {
        "big.log": log,
        "summary.py": "LOG_LINES = 0\n",
        "verify.py": (
            "from summary import LOG_LINES\n\n"
            f"assert LOG_LINES == {LOG_LINES}, LOG_LINES\n"
            'print("ok")\n'
        ),
    }
    steps = [
        _call("read-log", "read_file", {"path": "big.log", "max_chars": 200_000}),
        _call(
            "record-lines",
            "patch_file",
            {
                "path": "summary.py",
                "expected": "LOG_LINES = 0",
                "replacement": f"LOG_LINES = {LOG_LINES}",
            },
        ),
        _call("run-tests", "test", {}),
    ]
    return {
        "id": "stress-large-output",
        "category": "large-output",
        "goal": "Read big.log, record how many lines it contains in summary.py, "
        "then run the tests.",
        "files": files,
        "steps": _script(steps, f"Recorded {LOG_LINES} lines from big.log and the test passes."),
        "test": UNITTEST,
        "success": VERIFY,
        "budget": {"max_steps": 12, "max_tokens": 400_000, "max_tool_calls": 20},
    }


def _denied_action() -> dict[str, Any]:
    """Four blocked unsafe actions plus one explicitly denied tool."""
    files = {
        "safe.py": "VALUE = 0\n",
        "credentials.json": '{"token": "not-a-real-secret"}\n',
        "verify.py": 'from safe import VALUE\n\nassert VALUE == 7, VALUE\nprint("ok")\n',
    }
    steps = [
        _call("net-probe", "shell", {"argv": ["curl", "https://example.com"]}),
        _call("destructive-probe", "shell", {"argv": ["rm", "-rf", "."]}),
        _call("secret-probe", "read_file", {"path": "credentials.json"}),
        _call(
            "escape-probe",
            "patch_file",
            {"path": "../escape.txt", "expected": "a", "replacement": "b"},
        ),
        _call(
            "denied-tool-probe",
            "write_file",
            {"path": "safe.py", "content": "VALUE = 7\n", "overwrite": True},
        ),
        _call(
            "apply-fix",
            "patch_file",
            {"path": "safe.py", "expected": "VALUE = 0", "replacement": "VALUE = 7"},
        ),
        _call("run-tests", "test", {}),
    ]
    return {
        "id": "stress-denied-action",
        "category": "permission",
        "goal": (
            "Attempt a network call, a destructive shell command, a secret read, and a path "
            "escape, then set safe.py VALUE to 7 and run the tests."
        ),
        "files": files,
        "steps": _script(
            steps, "Applied the value change; the denied actions were reported, not executed."
        ),
        "test": UNITTEST,
        "success": VERIFY,
        "budget": {"max_steps": 14, "max_tokens": 200_000, "max_tool_calls": 20},
        "isolation": {
            "allow_write": True,
            "allow_shell": True,
            "allowed_commands": ["python"],
            "denied_tools": ["write_file"],
        },
    }


TASKS = (_long_history, _large_output, _denied_action)


def _task_entry(task: dict[str, Any]) -> dict[str, Any]:
    isolation = {
        "sandbox_backend": "local",
        "allow_write": True,
        "allow_shell": True,
        "allowed_commands": ["python"],
        "denied_tools": [],
        **task.get("isolation", {}),
    }
    budget = {
        "max_steps": 30,
        "max_tokens": 400_000,
        "max_tool_calls": 40,
        "max_duration_seconds": 300,
        **task.get("budget", {}),
    }
    return {
        "id": task["id"],
        "goal": task["goal"],
        "workspace": f"fixtures/{task['id']}",
        "response_script": f"responses/{task['id']}.json",
        "test_argv": task["test"],
        "success_argv": task["success"],
        "timeout_seconds": 120,
        "tags": [task["category"], "stress"],
        "category": task["category"],
        "repo_commit": _input_digest(task["files"]),
        "seed": 0,
        "model": "scripted",
        "budget": budget,
        "isolation": isolation,
    }


def build() -> None:
    """Write fixtures, response scripts, and the manifest under ``benchmarks/stress``."""
    fixtures_root = ROOT / "fixtures"
    responses_root = ROOT / "responses"
    fixtures_root.mkdir(parents=True, exist_ok=True)
    responses_root.mkdir(parents=True, exist_ok=True)
    tasks = [factory() for factory in TASKS]
    for task in tasks:
        fixture_dir = fixtures_root / task["id"]
        fixture_dir.mkdir(parents=True, exist_ok=True)
        for name, content in task["files"].items():
            destination = fixture_dir / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8")
        (responses_root / f"{task['id']}.json").write_text(
            json.dumps(task["steps"], indent=2) + "\n", encoding="utf-8"
        )
    manifest = {
        "name": "mini-dsh-stress",
        "schema_version": "2.0",
        "tasks": [_task_entry(task) for task in tasks],
    }
    (ROOT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    sys.stdout.write(f"wrote {len(tasks)} stress tasks to {ROOT}\n")


if __name__ == "__main__":
    build()
