def _write(root: Path, files: dict[str, str]) -> None:
    for name, body in files.items():
        target = root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text((HEADER if name.endswith(".py") else "") + body, encoding="utf-8")


def _read(root: Path) -> dict[str, str]:
    return {
        file.relative_to(root).as_posix(): file.read_text(encoding="utf-8")
        for file in sorted(root.rglob("*"))
        if file.is_file()
    }


def _suite(test_body: str) -> str:
    return (
        "import unittest\n\n" + test_body + "\n\nif __name__ == '__main__':\n    unittest.main()\n"
    )


def _overlay(test_body: str) -> dict[str, str]:
    return {
        "run_verification.py": build_hard.VERIFIER_SCRIPT,
        "verification_tests/__init__.py": "",
        "verification_tests/test_contract.py": _suite(test_body),
    }


def _task(  # noqa: PLR0913, PLR0917 - fixture declaration has six independent parts
    task_id: str,
    category: str,
    goal: str,
    files: dict[str, str],
    solution: dict[str, str],
    checks: str,
) -> dict[str, object]:
    tests = _suite(checks)
    # The agent sees the specification and a small runnable smoke suite. The
    # held-out copy is installed only after it has completed its work.
    return {
        "id": task_id,
        "category": category,
        "goal": goal,
        "fixture": {**files, "tests/__init__.py": "", "tests/test_smoke.py": tests},
        "solution": solution,
        "overlay": _overlay(checks),
    }


