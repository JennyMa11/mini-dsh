def main(root: Path = ROOT) -> None:
    """Write all 26 task trees and a manifest with full content hashes."""
    tasks = (
        _repo_tasks()
        + _hard_tasks()
        + _bug_tasks()
        + _refactor_tasks()
        + _test_repair_tasks()
        + _navigation_tasks()
    )
    assert len(tasks) == TASK_COUNT
    if root.exists():
        shutil.rmtree(root)
    manifest_tasks: list[dict[str, object]] = []
    for task in tasks:
        task_id = str(task["id"])
        fixture = task["fixture"]
        overlay = task["overlay"]
        solution = task["solution"]
        assert isinstance(fixture, dict)
        assert isinstance(overlay, dict)
        assert isinstance(solution, dict)
        workspace = root / "fixtures" / task_id
        verifier = root / "verification" / task_id
        reference = root / "solutions" / task_id
        if task_id.startswith(("repo-", "hard-")):
            build_hard._write(workspace, fixture)
            build_hard._write(verifier, overlay)
            build_hard._write(reference, solution)
        else:
            _write(workspace, fixture)
            _write(verifier, overlay)
            _write(reference, solution)
        manifest_tasks.append(
            {
                "id": task_id,
                "goal": task["goal"],
                "workspace": f"fixtures/{task_id}",
                "verification_overlay": f"verification/{task_id}",
                "success_argv": ["python", "run_verification.py"],
                "test_argv": VISIBLE,
                "category": task["category"],
                "tags": ["formal", str(task["category"])],
                "repo_commit": frozen_tree_digest(workspace),
                "verification_commit": frozen_tree_digest(verifier),
                "solution_commit": frozen_tree_digest(reference),
                "seed": 0,
                "model": "provider",
                "budget": BUDGET,
                "isolation": ISOLATION,
                "timeout_seconds": 120,
            }
        )
    root.mkdir(parents=True, exist_ok=True)
    (root / "manifest.json").write_text(
        json.dumps(
            {
                "name": "mini-dsh-local-formal-v1",
                "schema_version": "3.0",
                "tasks": manifest_tasks,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    sys.stdout.write(f"wrote {len(tasks)} frozen tasks to {root}\n")


if __name__ == "__main__":
    main()
