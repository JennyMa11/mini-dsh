"""Generate the Mini-dsh core benchmark fixtures, response scripts, and manifest.

The generated artifacts are committed so the suite runs without this script, but
they stay reproducible: run ``python benchmarks/build_core.py`` to rewrite them.
Each task pins its input with a ``sha256:`` digest of the fixture contents.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent / "core"
UNITTEST = ["python", "-m", "unittest", "discover", "-s", "."]
VERIFY = ["python", "verify.py"]
GENERATED_HEADER = "# Generated by benchmarks/build_core.py; edit the generator instead.\n"


def _fixture(files: dict[str, str]) -> dict[str, str]:
    """Return fixture files with a generated-source header on Python modules."""
    rendered: dict[str, str] = {}
    for name, content in files.items():
        rendered[name] = GENERATED_HEADER + content if name.endswith(".py") else content
    return rendered


def _input_digest(files: dict[str, str]) -> str:
    """Pin the fixture contents with a deterministic content digest."""
    digest = hashlib.sha256()
    for name in sorted(files):
        digest.update(name.encode())
        digest.update(files[name].encode())
    return f"sha256:{digest.hexdigest()[:16]}"


def _call(call_id: str, name: str, arguments: dict[str, Any]) -> dict[str, Any]:
    return {"call_id": call_id, "name": name, "arguments": arguments}


def _responses(task: dict[str, Any]) -> list[dict[str, Any]]:
    """Build a deterministic scripted response sequence for one task.

    ``input_tokens`` is deliberately omitted. The scripted adapter then measures the
    context it actually received, so a context-strategy ablation compares a real
    measured quantity instead of a number baked into the script.
    """
    script: list[dict[str, Any]] = []
    counter = 0

    def next_id() -> str:
        nonlocal counter
        counter += 1
        return f"c{counter}"

    def tool_step(calls: list[dict[str, Any]], output_tokens: int) -> dict[str, Any]:
        return {"tool_calls": calls, "output_tokens": output_tokens}

    if task["reads"]:
        script.append(
            tool_step(
                [_call(next_id(), "read_file", {"path": path}) for path in task["reads"]],
                5,
            )
        )
    if task["edits"]:
        script.append(
            tool_step(
                [
                    _call(
                        next_id(),
                        "patch_file",
                        {"path": path, "expected": expected, "replacement": replacement},
                    )
                    for path, expected, replacement in task["edits"]
                ],
                10,
            )
        )
    if task["writes"]:
        script.append(
            tool_step(
                [
                    _call(next_id(), "write_file", {"path": path, "content": content})
                    for path, content in task["writes"]
                ],
                8,
            )
        )
    script.append(tool_step([_call(next_id(), "test", {})], 5))
    script.append({"content": task["answer"], "output_tokens": 8})
    return script


def _bug_fix(  # noqa: PLR0913, PLR0917 - explicit fixture fields stay positional
    task_id: str,
    module: str,
    broken: str,
    fixed: str,
    test_body: str,
    goal: str,
) -> dict[str, Any]:
    function = broken.partition("(")[0].removeprefix("def ").strip()
    return {
        "id": task_id,
        "category": "bug-fix",
        "goal": goal,
        "files": _fixture(
            {
                f"{module}.py": f"{broken}\n",
                f"test_{module}.py": (
                    "import unittest\n\n"
                    f"from {module} import {function}\n\n\n"
                    "class TestCase(unittest.TestCase):\n"
                    f"{test_body}\n\n\n"
                    'if __name__ == "__main__":\n    unittest.main()\n'
                ),
            }
        ),
        "reads": [f"{module}.py"],
        "edits": [(f"{module}.py", broken, fixed)],
        "writes": [],
        "test": UNITTEST,
        "success": UNITTEST,
        "answer": f"Fixed {function} in {module}.py and verified the unit test passes.",
    }


def _feature(  # noqa: PLR0913, PLR0917 - explicit fixture fields stay positional
    task_id: str,
    module: str,
    existing: str,
    added: str,
    function: str,
    test_body: str,
    goal: str,
) -> dict[str, Any]:
    return {
        "id": task_id,
        "category": "feature",
        "goal": goal,
        "files": _fixture(
            {
                f"{module}.py": f"{existing}\n",
                f"test_{module}.py": (
                    "import unittest\n\n"
                    f"from {module} import {function}\n\n\n"
                    "class TestCase(unittest.TestCase):\n"
                    f"{test_body}\n\n\n"
                    'if __name__ == "__main__":\n    unittest.main()\n'
                ),
            }
        ),
        "reads": [f"{module}.py"],
        "edits": [(f"{module}.py", existing, f"{existing}\n\n\n{added}")],
        "writes": [],
        "test": UNITTEST,
        "success": UNITTEST,
        "answer": f"Implemented {function} in {module}.py and verified the tests pass.",
    }


def _test_repair(  # noqa: PLR0913, PLR0917 - explicit fixture fields stay positional
    task_id: str,
    module: str,
    source: str,
    function: str,
    wrong: str,
    right: str,
    goal: str,
) -> dict[str, Any]:
    return {
        "id": task_id,
        "category": "test-repair",
        "goal": goal,
        "files": _fixture(
            {
                f"{module}.py": f"{source}\n",
                f"test_{module}.py": (
                    "import unittest\n\n"
                    f"from {module} import {function}\n\n\n"
                    "class TestCase(unittest.TestCase):\n"
                    f"    def test_value(self) -> None:\n        self.assertEqual({wrong})\n\n\n"
                    'if __name__ == "__main__":\n    unittest.main()\n'
                ),
            }
        ),
        "reads": [f"test_{module}.py"],
        "edits": [(f"test_{module}.py", wrong, right)],
        "writes": [],
        "test": UNITTEST,
        "success": UNITTEST,
        "answer": f"Repaired the incorrect assertion for {function} without touching {module}.py.",
    }


def _refactor(  # noqa: PLR0913, PLR0917 - explicit fixture fields stay positional
    task_id: str,
    module: str,
    function: str,
    body: str,
    expected_value: str,
    goal: str,
) -> dict[str, Any]:
    return {
        "id": task_id,
        "category": "refactor",
        "goal": goal,
        "files": _fixture(
            {
                f"{module}.py": f"def {function}(values: list[int]) -> int:\n{body}\n",
                "verify.py": (
                    "from pathlib import Path\n\n"
                    f"import {module}\n\n"
                    f"assert {module}.{function}([1, 2, 3]) == {expected_value}\n"
                    f'assert "sum(" in Path("{module}.py").read_text(encoding="utf-8")\n'
                    'print("refactor verified")\n'
                ),
            }
        ),
        "reads": [f"{module}.py"],
        "edits": [
            (
                f"{module}.py",
                f"def {function}(values: list[int]) -> int:\n{body}",
                f"def {function}(values: list[int]) -> int:\n    return sum(values)",
            )
        ],
        "writes": [],
        "test": VERIFY,
        "success": VERIFY,
        "answer": f"Refactored {function} to use sum while preserving behavior.",
    }


def _understanding(  # noqa: PLR0913, PLR0917 - explicit fixture fields stay positional
    task_id: str,
    module: str,
    source: str,
    answer: dict[str, Any],
    checks: list[str],
    goal: str,
) -> dict[str, Any]:
    return {
        "id": task_id,
        "category": "code-understanding",
        "goal": goal,
        "files": _fixture(
            {
                f"{module}.py": source,
                "verify.py": (
                    "import json\n"
                    "from pathlib import Path\n\n"
                    "data = json.loads(Path('answer.json').read_text(encoding='utf-8'))\n"
                    + "".join(f"assert {check}\n" for check in checks)
                    + 'print("answer verified")\n'
                ),
            }
        ),
        "reads": [f"{module}.py"],
        "edits": [],
        "writes": [("answer.json", json.dumps(answer, indent=2, sort_keys=True) + "\n")],
        "test": VERIFY,
        "success": VERIFY,
        "answer": f"Recorded the defaults for {module}.py in answer.json.",
    }


def _multi_file(  # noqa: PLR0913, PLR0917 - explicit fixture fields stay positional
    task_id: str,
    goal: str,
    first: tuple[str, str, str],
    second: tuple[str, str, str],
    test_body: str,
    test_imports: str,
    answer: str,
) -> dict[str, Any]:
    first_path, first_broken, first_fixed = first
    second_path, second_broken, second_fixed = second
    return {
        "id": task_id,
        "category": "multi-file",
        "goal": goal,
        "files": _fixture(
            {
                first_path: f"{first_broken}\n",
                second_path: f"{second_broken}\n",
                "test_behavior.py": (
                    "import unittest\n\n"
                    f"{test_imports}\n\n\n"
                    "class TestCase(unittest.TestCase):\n"
                    f"{test_body}\n\n\n"
                    'if __name__ == "__main__":\n    unittest.main()\n'
                ),
            }
        ),
        "reads": [second_path, first_path],
        "edits": [
            (second_path, second_broken, second_fixed),
            (first_path, first_broken, first_fixed),
        ],
        "writes": [],
        "test": UNITTEST,
        "success": UNITTEST,
        "answer": answer,
    }


