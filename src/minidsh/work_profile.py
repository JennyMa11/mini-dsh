"""Explicit full-capability launcher for this repository's development workspace."""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from minidsh.cli import main as cli_main
from minidsh.config import resolve_config

IMAGE = "mini-dsh-work:local"
TOOLS = (
    "read_file",
    "write_file",
    "patch_file",
    "search",
    "list_files",
    "search_code",
    "find_symbol",
    "git",
    "shell",
    "test",
    "build",
    "load_skill",
    "propose_memory",
)


def full_work_config(workspace: Path, storage_root: Path) -> str:
    """Describe the mini_dsh project explicitly; parsing does not create storage."""
    workspace, storage_root = workspace.resolve(), storage_root.resolve()
    if storage_root.is_relative_to(workspace):
        raise ValueError("Memory storage must be outside the workspace")
    return "\n".join(
        (
            "# Generated by mini-dsh-work; no credentials or automatic approvals.",
            "[minidsh]",
            "allow_write = true",
            "allow_shell = true",
            'approval_mode = "ask"',
            'sandbox_backend = "docker"',
            f"docker_image = {json.dumps(IMAGE)}",
            "progressive_tools_enabled = true",
            "normalize_tool_results = true",
            f"enabled_tools = {json.dumps(TOOLS)}",
            'allowed_commands = ["git", "uv", "python", "python3", "pytest", "ruff", "mypy"]',
            'test_command = ["uv", "run", "--no-sync", "pytest", "-q"]',
            'build_command = ["uv", "build", "--no-build-isolation"]',
            'skill_roots = ["examples/skills"]',
            "multi_agent_enabled = false",
            "",
            "[minidsh.verification]",
            'argv = ["uv", "run", "--no-sync", "pytest", "-q"]',
            'criterion_version = "mini_dsh_work_v1"',
            "timeout_seconds = 300",
            "",
            "[minidsh.memory]",
            'project_id = "mini_dsh"',
            'applicable_version = "work_v1"',
            f"storage_root = {json.dumps(str(storage_root))}",
            f"database = {json.dumps(str(storage_root / 'memory.sqlite3'))}",
            "",
        )
    )


def _docker_ready(workspace: Path) -> None:
    result = subprocess.run(
        ["docker", "info", "--format", "{{.ServerVersion}}"],
        cwd=workspace,
        capture_output=True,
        text=True,
        timeout=15,
        check=False,
    )
    if result.returncode:
        raise RuntimeError("Docker is not running. Start Docker Desktop and retry.")


def _image_ready(workspace: Path, *, rebuild: bool) -> None:
    result = subprocess.run(
        ["docker", "image", "inspect", IMAGE],
        cwd=workspace,
        capture_output=True,
        timeout=15,
        check=False,
    )
    if rebuild or result.returncode:
        subprocess.run(
            ["docker", "build", "-f", "docker/work.Dockerfile", "-t", IMAGE, "."],
            cwd=workspace,
            timeout=900,
            check=True,
        )


def main() -> None:
    """Prepare the isolated development image, then enter the existing work UI."""
    parser = argparse.ArgumentParser(description="Start all Mini-dsh development capabilities.")
    parser.add_argument("--memory-root", type=Path)
    parser.add_argument("--rebuild-image", action="store_true")
    parser.add_argument("--check", action="store_true", help="check setup without calling a model")
    args, forwarded = parser.parse_known_args()
    workspace = Path.cwd().resolve()
    if (
        not (workspace / "docker/work.Dockerfile").is_file()
        or not (workspace / "examples/skills").is_dir()
    ):
        parser.error("run mini-dsh-work from the Mini-dsh repository root")
    storage = args.memory_root or workspace.parent / ".mini-dsh-private" / "mini_dsh"
    try:
        content = full_work_config(workspace, storage)
        # Docker Desktop's CLI may not be on a GUI-launched process's PATH.
        if shutil.which("docker") is None:
            desktop = Path("/Applications/Docker.app/Contents/Resources/bin")
            if (desktop / "docker").is_file():
                os.environ["PATH"] = str(desktop) + os.pathsep + os.environ.get("PATH", "")
        _docker_ready(workspace)
        _image_ready(workspace, rebuild=args.rebuild_image)
        storage = storage.resolve()
        storage.mkdir(mode=0o700, parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix="mini-dsh-work-") as directory:
            config = Path(directory) / "work.toml"
            config.write_text(content, encoding="utf-8")
            if args.check:
                resolve_config(config_path=config, environ={})
                sys.stdout.write(
                    "Ready: 13 tools; Skills, Verification and Memory enabled; "
                    "Docker isolated; per-operation approval.\n"
                    f"Memory storage: {storage}\n"
                )
                return
            cli_main(["work", "--config", str(config), *forwarded])
    except (OSError, RuntimeError, ValueError, subprocess.SubprocessError) as exc:
        parser.exit(1, f"Full startup failed: {exc}\n")
